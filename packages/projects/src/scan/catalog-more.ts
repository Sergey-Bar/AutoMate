/**
 * The expanded toolbox: free and commercial tools for every capability.
 *
 * ## Tiers, as of October 2026, and never prices
 *
 * `pricing` is the adoption tier read from each vendor's public page in October 2026:
 * `free` needs no paid plan for real use, `freemium` has a usable free tier, `paid` needs a
 * licence or subscription. Prices are not recorded — they change monthly and vary by seat
 * and region — and every `paid` tool links its vendor page instead (the catalogue test
 * refuses one without).
 *
 * ## A paid tool is never recommended
 *
 * A recommendation is the product picking for you, and it only picks what you can adopt
 * today without a purchase order. Paid tools are `in-use` when the scan finds them and
 * `available` otherwise.
 *
 * ## Detection is evidence or nothing
 *
 * Each entry names a dependency or a file the tool owns where one exists. A SaaS that
 * leaves nothing in a repository (Xray, Zephyr, Functionize) has no signal, so it can only
 * ever be `available` — the scan never claims a tool is in use on a guess.
 */
