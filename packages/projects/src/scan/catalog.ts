/**
 * The QA toolbox: every tool the product knows how to recognise and recommend.
 *
 * ## A catalogue entry is a claim the scan can check
 *
 * Each entry names the evidence that proves the tool is in use — a dependency, or a
 * file the tool owns. An entry with no checkable signal would be recommended to every
 * repository forever, including the ones that already use it, and a recommendation the
 * reader can see is wrong teaches them to ignore the rest.
 *
 * `setup` is text a person copies. The product never runs it: installing a dependency
 * into someone's repository is a change they review, not a button.
 */
export interface CatalogTool {
  id: string;
  name: string;
  /** The adoption tier. Never a price: see `ToolPricingSchema`. */
  pricing: ToolPricing;
  /** The vendor's pricing or product page. Required for `paid`, by the catalogue test. */
  vendorUrl?: string;
  capability: QaCapability;
  ecosystems: readonly string[];
  description: string;
  setup: string;
  docsUrl: string;
  /** Package names (npm, PyPI, Maven artifact, gem, crate) whose presence proves use. */
  dependencies?: readonly string[];
  /** Repo-relative path patterns whose presence proves use. */
  files?: readonly RegExp[];
  /** The default recommendation for its capability in its ecosystems. */
  preferred?: boolean;
}

