#!/usr/bin/env node
/**
 * `pnpm authz:check` / `pnpm authz:matrix` - the authz matrix, generated from the composed API.
 *
 * Imports the built application (`apps/api/dist`) in its test composition, reads every route
 * Hono registered and the credential checks tagged onto them, and compares the result with
 * `docs/quality/authz-matrix.json`:
 *
 *   node scripts/authz-matrix.mjs           check: exit 1 on a missing, stale or disagreeing row
 *   node scripts/authz-matrix.mjs --write   rewrite the matrix (a deliberate act, never CI)
 *
 * It needs `pnpm build` first and says so, rather than reporting a clean matrix over nothing.
 * `apps/api/src/authz-matrix.test.ts` is the other half: it sends real requests to every row
 * and fails when behaviour disagrees with the access class.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  buildMatrix,
  compareMatrix,
  summarise,
  unevidencedGuardedRoutes,
} from './lib/authz-matrix.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MATRIX = 'docs/quality/authz-matrix.json';
const DIST = 'apps/api/dist';

/**
 * @param {string} directory
 * @param {string[]} out
 * @returns {string[]}
 */
function testFiles(directory, out = []) {
  if (!existsSync(directory)) return out;
  for (const name of readdirSync(directory)) {
    if (name === 'node_modules' || name === 'dist' || name === 'coverage') continue;
    const full = path.join(directory, name);
    if (statSync(full).isDirectory()) testFiles(full, out);
    else if (/\.(test|spec)\.tsx?$/.test(name)) out.push(full);
  }
  return out;
}

/** @returns {import('./lib/authz-matrix.mjs').TestFile[]} */
function readTests() {
  return [path.join(root, 'apps/api/src'), path.join(root, 'tests')]
    .flatMap((directory) => testFiles(directory))
    .map((full) => ({
      path: path.relative(root, full).split(path.sep).join('/'),
      text: readFileSync(full, 'utf8'),
    }));
}

/**
 * The route groups the API serves: the composed app, and the groups it mounts only with a
 * database, which the in-memory composition cannot reach.
 *
 * @returns {Promise<Array<{ routes: import('./lib/authz-matrix.mjs').RegisteredRoute[], composition: string }>>}
 */
async function loadGroups() {
  process.env['NODE_ENV'] = 'test';
  const entry = path.join(root, DIST, 'index.js');
  if (!existsSync(entry)) {
    throw new Error(`${DIST}/index.js does not exist. Run \`pnpm build\` first.`);
  }
  const { app } =
    /** @type {{ app: { routes: import('./lib/authz-matrix.mjs').RegisteredRoute[] } }} */ (
      await import(pathToFileURL(entry).href)
    );
  // Registered by `index.ts` only when a database exists. Constructing the group reads no
  // option at registration time, so the routes are listed without one.
  const projects =
    /** @type {{ createProjectsRoutes: (options: object) => { routes: import('./lib/authz-matrix.mjs').RegisteredRoute[] } }} */ (
      await import(pathToFileURL(path.join(root, DIST, 'routes/projects.js')).href)
    );
  return [
    { routes: app.routes, composition: 'always' },
    { routes: projects.createProjectsRoutes({}).routes, composition: 'database' },
  ];
}

const write = process.argv.includes('--write');
const groups = await loadGroups().catch((/** @type {unknown} */ error) => {
  console.error(`authz-matrix: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(2);
});
const tests = readTests();
const rows = buildMatrix(groups, tests);
const document = {
  version: 1,
  what: 'Every route the composed API registers, and who may call it. Generated by `pnpm authz:matrix`; do not edit.',
  how: [
    '`access` is read from the credential checks tagged onto the route (`apps/api/src/http/access.ts`), not typed. A route with none is `open`: ADR-006 gives the install no user authentication.',
    '`workspaceScoped` is true when the endpoint handler names the workspace. It is a prompt to look for a filter, not proof of one: `tenancy-scope.json` and the isolation tests are the proof.',
    '`evidenceTest` is the first test file that names the route. `apps/api/src/authz-matrix.test.ts` sends a request with no credential to every row and fails when the answer disagrees with `access`.',
    '`composition: database` rows are mounted only when `DATABASE_URL` is set, so the in-memory composition cannot send them a request; the class is still read from their guards.',
  ],
  summary: summarise(rows),
  routes: rows,
};

if (write) {
  writeFileSync(path.join(root, MATRIX), `${JSON.stringify(document, null, 2)}\n`);
  console.log(`authz-matrix: wrote ${String(rows.length)} routes to ${MATRIX}`);
  console.log(JSON.stringify(document.summary));
  process.exit(0);
}

const committedPath = path.join(root, MATRIX);
if (!existsSync(committedPath)) {
  console.error(`authz-matrix: ${MATRIX} does not exist. Run \`pnpm authz:matrix\`.`);
  process.exit(1);
}
const committed =
  /** @type {{ routes?: import('./lib/authz-matrix.mjs').Row[] }} */ (
    JSON.parse(readFileSync(committedPath, 'utf8'))
  ).routes ?? [];
const findings = [...compareMatrix(committed, rows, tests), ...unevidencedGuardedRoutes(rows)];
if (findings.length > 0) {
  console.error(`authz-matrix: ${String(findings.length)} problem(s)`);
  for (const finding of findings) console.error(`  - ${finding}`);
  console.error('Run `pnpm authz:matrix` to regenerate after a deliberate change.');
  process.exit(1);
}
console.log(`authz-matrix: ${String(rows.length)} routes agree with ${MATRIX}`);
console.log(JSON.stringify(document.summary));
process.exit(0);
